// Helper functions for reviews management & persistence
const LOCAL_STORAGE_KEY = 'beyond_kanchenjunga_user_reviews';
const HELPFUL_VOTES_KEY = 'beyond_kanchenjunga_helpful_votes';

export function getAllReviews(): Review[] {
  if (typeof window === 'undefined') {
    return initialReviewsData;
  }
  try {
    const stored = localStorage.getItem(LOCAL_STORAGE_KEY);
    if (!stored) return initialReviewsData;
    const userReviews: Review[] = JSON.parse(stored);
    return [...userReviews, ...initialReviewsData];
  } catch {
    return initialReviewsData;
  }
}

export function saveUserReview(review: Omit<Review, 'id' | 'date' | 'helpfulVotes' | 'verified' | 'userCreated'>): Review {
  const newReview: Review = {
    ...review,
    id: `user-rev-${Date.now()}`,
    date: 'Just now',
    helpfulVotes: 0,
    verified: true,
    userCreated: true,
  };

  try {
    const existing = localStorage.getItem(LOCAL_STORAGE_KEY);
    const list: Review[] = existing ? JSON.parse(existing) : [];
    list.unshift(newReview);
    localStorage.setItem(LOCAL_STORAGE_KEY, JSON.stringify(list));
  } catch (e) {
    console.error('Failed to save review to localStorage', e);
  }

  return newReview;
}

export function getHelpfulVoteIds(): string[] {
  if (typeof window === 'undefined') return [];
  try {
    const votes = localStorage.getItem(HELPFUL_VOTES_KEY);
    return votes ? JSON.parse(votes) : [];
  } catch {
    return [];
  }
}

export function toggleHelpfulVote(reviewId: string): boolean {
  if (typeof window === 'undefined') return false;
  try {
    const votes = getHelpfulVoteIds();
    let updated: string[];
    let isAdded = false;
    if (votes.includes(reviewId)) {
      updated = votes.filter((id) => id !== reviewId);
      isAdded = false;
    } else {
      updated = [...votes, reviewId];
      isAdded = true;
    }
    localStorage.setItem(HELPFUL_VOTES_KEY, JSON.stringify(updated));
    return isAdded;
  } catch {
    return false;
  }
}
