export interface IrctcTrainSchedule {
  trainNumber: string;
  trainName: string;
  originStationCode: 'SDAH' | 'HWH' | 'KOAA' | 'SHM' | 'DKAE';
  originStationName: string;
  departureTime: string; // 24-hr format e.g. "22:05"
  destinationStationCode: 'NJP' | 'SGUJ';
  destinationStationName: string;
  arrivalTime: string; // 24-hr format e.g. "08:30"
  duration: string; // e.g. "10h 25m"
  runsOn: string[]; // e.g. ['Daily'] or ['Mon', 'Tue', ...]
  classes: string[]; // e.g. ['1A', '2A', '3A', '3E', 'SL']
  trainType: 'Vande Bharat' | 'Superfast' | 'Express' | 'Shatabdi' | 'Intercity' | 'Special';
  timingCategory: 'Overnight' | 'Morning' | 'Afternoon' | 'Evening';
  kalyaniSuburbanStop?: {
    stationName: string;
    stationCode: string;
    distanceFromKalyani: string;
    scheduledHaltTime: string;
    commuterTip: string;
  };
  keyHighlights: string;
  recommendedFor: string;
  pantryAvailable: boolean;
  njpPickupPortico: string;
}

